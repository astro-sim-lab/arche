// ---------------------------------------------------------------------------
// composition_of — registered composition of one catalog species.
//   `.known == false` only for an id outside the catalog.  build_invariants()
//   fails the whole matrix closed on the first unknown species, so adding a
//   species to the catalog without adding it here disables the projection for
//   that network rather than asserting a wrong law.
// ---------------------------------------------------------------------------
inline constexpr Composition composition_of(SpId id) {
  for (const detail::Row& r : detail::kCatalog) {
    if (r.id == id) return Composition{r.n, r.q, true};
  }
  return Composition{};
}

