// One row per catalog species, no more and no less.  Without this a species
// added to species_catalog.h but not here would fail CLOSED at run time
// (composition_of() returns known == false, build_invariants() returns 0, the
// projection silently stops for that whole network) -- safe, but silent.  Fail
// at compile time instead.  Mirrors the same guard on kSpeciesCatalog
// (core/species_catalog.h).
static_assert(std::size(kCatalog) == static_cast<std::size_t>(SpId::Count),
              "kCatalog must have exactly one row per SpId; regenerate it with "
              "tools/python/derive_composition.py --emit-cxx");

