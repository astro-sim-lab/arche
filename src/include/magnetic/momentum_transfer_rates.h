// momentum_transfer_rates.h — charged-particle/neutral momentum-transfer rate
// coefficients <sigma v>(T) at zero drift velocity
//
// Tabulated pairs: e-H, e-H2, e-He, H+-H, H+-H2, H+-He, H3+-H2, HCO+-H2,
// C+-H.  Units cm^3 s^-1.
//
// Definition (Pinto & Galli 2008, A&A 484, 17, eq. 8, limit v_d -> 0):
//   <sigma v> = (4/3) sqrt(8 k T / (pi mu)) * (1/2) (k T)^-3
//               * Int_0^inf sigma_mt(E) E^2 exp(-E / k T) dE,
// with sigma_mt the momentum-transfer cross section, E the centre-of-mass
// collision energy and mu the reduced mass.  Constants: k = 1.380649e-16 erg/K,
// 1 eV = 1.602176634e-12 erg, m_e = 9.109383714e-28 g, atomic mass constant
// 1.66053906892e-24 g, a_0^2 = (5.29177210544e-9 cm)^2; masses H 1.00783,
// H2 2.01565, He 4.0026, H+ 1.00728, H3+ 3.02293, HCO+ 29.00219, C+ 11.99945
// (species_catalog.h).
//
// Cross sections:
//   e-H   Dalgarno, Yan & Liu 1999, ApJS 125, 237 (Fig. 1b), as plotted in
//         Pinto & Galli 2008, Fig. 14 (solid curve), 1e-3-1e3 eV, read from
//         the figure.  Log-log interpolation; constant below 1e-3 eV
//         (zero-energy limit); above 1e3 eV the power law of the last interval.
//   e-H2  IST-Lisbon database (www.lxcat.net, retrieved 2026-10-15; Alves 2014,
//         J. Phys. Conf. Ser. 565, 012007), ELASTIC, set of Baghel, Marques &
//         Alves 2026, Plasma Sources Sci. Technol. 35, 085023; 0-1e4 eV.
//   e-He  IST-Lisbon database (as above), ELASTIC, set of Alves et al. 2013,
//         J. Phys. D 46, 334002 and Santos et al. 2014, J. Phys. D 47, 265201
//         (Crompton et al. 1970; Milloy & Crompton 1977; Register et al. 1980;
//         Belmonte et al. 2007); 0-1e3 eV.
//         For both IST-Lisbon sets: linear interpolation and zero above the
//         last energy, as the database prescribes.
//   H+-H  Schultz, Krstic, Lee & Raymond 2008, ApJ 678, 950 (Fig. 8 data;
//         below 1e2 eV from Glassgold, Krstic & Schultz 2005, ApJ 621, 808),
//         1e-4-1e6 eV.  Energies are given to 3 digits; rows with the same
//         energy are averaged.  Log-log interpolation; below 1e-4 eV
//         sigma ~ E^-1/2 (polarization limit) joined to the first point.
//   H+-H2 Krstic & Schultz 1999a (Atomic and Plasma-Material Interaction Data
//         for Fusion 8, 1) and 1999c (Phys. Rev. A 60, 2118), fully quantal, as
//         plotted in Pinto & Galli 2008, Fig. 6 (solid curve), 0.10-76 eV,
//         read from the figure.  Log-log interpolation; below 0.10 eV
//         sigma = 1.05e-15 (E/eV)^-0.531 cm^2 (Pinto & Galli 2008); above, the
//         power law of the last interval.
//   H+-He Krstic & Schultz 1999a and 1999b (J. Phys. B 32, 2415),
//         semiclassical, as plotted in Pinto & Galli 2008, Fig. 16 (solid
//         curve), 0.099-90 eV, read from the figure.  Log-log interpolation;
//         below 0.099 eV the Langevin cross section
//         2.41 pi sqrt(alpha e^2 / (2 E)), alpha_He = 0.207e-24 cm^3 (Pinto &
//         Galli 2008); above, the power law of the last interval.
//   H3+-H2 Phelps 1990, J. Phys. Chem. Ref. Data 19, 653, as plotted in Pinto
//         & Galli 2008, Fig. 4 (solid curve, centre-of-mass energy), 0.04-4e3
//         eV, read from the figure.  Log-log interpolation; below 0.04 eV
//         sigma = 1.62e-15 (E/eV)^-0.507 cm^2 (Pinto & Galli 2008); above, the
//         power law of the last interval.
//   HCO+-H2 Flower 2000, MNRAS 313, L19 (erratum 315, 431), the computed
//         points of Pinto & Galli 2008, Fig. 2, 8.6e-4-0.60 eV, read from the
//         figure.  Interpolation linear in sigma against log E; below the
//         first point sigma ~ E^-1/2; above the last point the power law
//         fitted (least squares in log-log) to the points of the last decade.
//   C+-H  Flower & Pineau des Forets 1995, MNRAS 275, 1049, as interpolated in
//         Pinto & Galli 2008, Fig. 10 (solid curve), 1e-5-10 eV, read from the
//         figure.  Log-log interpolation; below 1e-5 eV sigma ~ E^-1/2; above,
//         the power law of the last interval.
//
// Grid: log10(T/K) = 0, 0.01, ..., 6 (601 points).  mt_rate() interpolates
// linearly in (log T, log <sigma v>); the interpolation error is below 6e-5.
// Below 1 K: <sigma v> ~ T^1/2 for electrons (constant cross section) and
// constant for ions (sigma ~ E^-1/2; for H+-H2 and H3+-H2 the table itself
// varies as T^-0.031 and T^-0.007 there).  Above 1e6 K: power law of the last
// interval.
// ---------------------------------------------------------------------------
