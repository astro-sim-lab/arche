// <sigma v>(T) [cm^3 s^-1] for one pair; quiet NaN unless T is positive and
// finite.
inline double mt_rate(MtPair pair, double T_K) noexcept {
  if (!(T_K > 0.0) || !std::isfinite(T_K))
    return std::numeric_limits<double>::quiet_NaN();
  const int p = static_cast<int>(pair);
  const double* r = detail::kMtRates[p];
  const double x = (std::log10(T_K) - kMtLog10TMin) / kMtDLog10T;
  if (x <= 0.0)
    return r[0] * std::pow(T_K / std::pow(10.0, kMtLog10TMin),
                           detail::kMtLowTSlope[p]);
  int i = static_cast<int>(x);
  if (i > kMtRateN - 2) i = kMtRateN - 2;
  const double f = x - i;
  return std::exp((1.0 - f) * std::log(r[i]) + f * std::log(r[i + 1]));
}

